#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AttentionSegment {
    pub query_start: usize,
    pub query_end: usize,
    /// Keys are the contiguous prefix `[0, key_end)`.
    pub key_end: usize,
    /// Causal attention uses bottom-right alignment when Q is a suffix of K.
    pub causal: bool,
}

/// Decompose Gemma3's two image-block overlay into causal text and unmasked
/// image-query intervals. Concatenating the five outputs restores token order.
pub fn prefix_attention_segments(
    config: &Dm05Config,
    token_ids: &[u32],
) -> Result<Vec<AttentionSegment>> {
    let [(first_start, first_end), (second_start, second_end)] =
        config.validate_prefix_tokens(token_ids)?;
    let boundaries = [
        (0, first_start, first_start, true),
        (first_start, first_end, first_end, false),
        (first_end, second_start, second_start, true),
        (second_start, second_end, second_end, false),
        (second_end, token_ids.len(), token_ids.len(), true),
    ];
    Ok(boundaries
        .into_iter()
        .filter(|(start, end, _, _)| start < end)
        .map(
            |(query_start, query_end, key_end, causal)| AttentionSegment {
                query_start,
                query_end,
                key_end,
                causal,
            },
        )
        .collect())
}

