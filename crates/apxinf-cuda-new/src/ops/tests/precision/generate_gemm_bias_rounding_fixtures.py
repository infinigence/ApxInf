"""Generate cancellation oracles; CUDA mode independently checks Torch Linear."""
from fractions import Fraction
from pathlib import Path
import argparse
import struct


def emit(name, values):
    result = ["#[rustfmt::skip]", f"pub(crate) const {name}: &[f32] = &["]
    for start in range(0, len(values), 8):
        result.append("    " + ", ".join(repr(float(x)) for x in values[start:start + 8]) + ",")
    result.append("];")
    return "\n".join(result)


def rounded(value, name):
    if name == "F16":
        return struct.unpack("e", struct.pack("e", float(value)))[0]
    word = struct.unpack("I", struct.pack("f", float(value)))[0]
    word = (word + 0x7FFF + ((word >> 16) & 1)) & 0xFFFF0000
    return struct.unpack("f", struct.pack("I", word))[0]


def exact_case(name, exponent):
    epsilon = Fraction(1, 2 ** exponent)
    a = [float(1 + epsilon) if column == 0 else 0.0
         for _ in range(4) for column in range(16)]
    b = [float(1 + (column + 1) * epsilon) if row == 0 else 0.0
         for row in range(16) for column in range(8)]
    bias = [-float(1 + (column + 2) * epsilon) for column in range(8)]
    assert all(rounded(value, name) == value for value in a + b + bias)
    expected = []
    double = []
    for _ in range(4):
        for column in range(8):
            projection = (1 + epsilon) * (1 + (column + 1) * epsilon)
            exact = projection - (1 + (column + 2) * epsilon)
            # Both the inputs and residuals are exactly representable in the
            # requested dtype, so the oracle has no reduction ambiguity.
            assert rounded(exact, name) == float(exact)
            expected.append(float(exact))
            double.append(rounded(rounded(projection, name) + bias[column], name))
    assert all(value != 0 for value in expected)
    assert all(value == 0 for value in double)
    return {"A": a, "B": b, "BIAS": bias,
            "EXPECTED": expected, "DOUBLE_ROUNDED": double}


parser = argparse.ArgumentParser()
parser.add_argument("--device", choices=["analytic", "cuda"], default="cuda")
parser.add_argument("--output", type=Path,
                    default=Path(__file__).with_name("gemm_bias_rounding_fixtures.rs"))
args = parser.parse_args()
if args.device == "cuda":
    import torch
    torch.backends.cuda.matmul.allow_tf32 = False
    provenance = f"PyTorch {torch.__version__}; CUDA F.linear checked against exact rational arithmetic."
else:
    provenance = "CPU exact-rational oracle; use --device cuda for independent F.linear verification."
parts = ["// @generated by generate_gemm_bias_rounding_fixtures.py; do not edit.",
         f"// {provenance}", "pub(crate) const M: usize = 4;",
         "pub(crate) const K: usize = 16;", "pub(crate) const N: usize = 8;"]
for name, exponent in [("BF16", 7), ("F16", 10)]:
    values = exact_case(name, exponent)
    if args.device == "cuda":
        dtype = torch.bfloat16 if name == "BF16" else torch.float16
        a = torch.tensor(values["A"], dtype=dtype, device="cuda").reshape(4, 16)
        b = torch.tensor(values["B"], dtype=dtype, device="cuda").reshape(16, 8)
        bias = torch.tensor(values["BIAS"], dtype=dtype, device="cuda")
        expected = torch.nn.functional.linear(a, b.T, bias)
        double = torch.mm(a, b) + bias
        assert expected.float().flatten().cpu().tolist() == values["EXPECTED"]
        assert double.float().flatten().cpu().tolist() == values["DOUBLE_ROUNDED"]
    for suffix, array in values.items():
        parts.append(emit(f"{name}_{suffix}", array))
args.output.write_text("\n\n".join(parts) + "\n")
