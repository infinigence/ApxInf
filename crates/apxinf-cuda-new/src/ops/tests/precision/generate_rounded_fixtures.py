"""Generate independent PyTorch goldens for rounded arithmetic and complex RoPE.

Run with torch installed, redirect stdout to torch_rounded_fixtures.rs.
"""
import math
import torch

torch.set_grad_enabled(False)
x = torch.tensor([[0.0171, -0.0781, 0.152, -0.314, 0.691, -1.17, 2.14, -3.91],
                  [4.21, -2.45, 1.015, -0.121, 0.333, 0.555, -0.777, 0.999]], dtype=torch.bfloat16, device="cuda")
w = torch.tensor([1.015, 0.875, 1.25, -0.75, 1.12, 0.9, -1.4, 0.33], dtype=torch.bfloat16, device="cuda")
y = torch.tensor([[0.231, -0.99, 0.121, 2.12, -0.833, 0.022, 0.71, 1.01],
                  [1.43, 0.271, -0.13, -0.88, 0.111, 2.33, -1.31, -0.451]], dtype=torch.bfloat16, device="cuda")
def emit(name, value):
    vals = value.flatten().cpu().float().tolist()
    print(f'pub const {name}: &[f32] = &[' + ', '.join(f'{v:.12e}f32' for v in vals) + '];')
print('// Generated by generate_rounded_fixtures.py with PyTorch ' + torch.__version__)
emit('X', x); emit('Y', y); emit('WEIGHT', w)
emit('RMS', (x.float() * torch.rsqrt(x.float().pow(2).mean(-1,keepdim=True) + 1e-6)).bfloat16() * w)
emit('GELU', 0.5*x*(1.0+torch.tanh(math.sqrt(2.0/math.pi)*(x+0.044715*torch.pow(x,3.0)))))
emit('EULER', x + y * torch.tensor(-0.1777,dtype=torch.bfloat16,device='cuda'))
emit('MULTIPLY', x*y); emit('ADD',x+y); emit('BROADCAST_MULTIPLY', x*w); emit('BROADCAST_ADD',x+w)
emit('ROW_MULTIPLY', x*torch.tensor([0.75,-0.25],dtype=torch.bfloat16,device='cuda').view(2,1))
angles = torch.arange(8,dtype=torch.float64,device='cuda').view(2,4) * 0.713
cs = torch.polar(torch.ones_like(angles),angles)
emit('ROPE_F32',torch.view_as_real(torch.view_as_complex(x.double().reshape(2,4,2))*cs).flatten(1).float())
emit('ROPE_BF16',torch.view_as_real(torch.view_as_complex(x.double().reshape(2,4,2))*cs).flatten(1).bfloat16())
print('pub const COEFFICIENTS: &[(f64,f64)] = &[' + ', '.join(f'({c:.17e}f64,{s:.17e}f64)' for c,s in zip(cs.real.flatten().cpu().tolist(),cs.imag.flatten().cpu().tolist())) + '];')
for dtype, prefix in [(torch.float16, 'F16'), (torch.float32, 'F32')]:
    a = x.to(dtype)
    b = y.to(dtype)
    weight = w.to(dtype)
    emit(prefix + '_X',a); emit(prefix + '_Y',b); emit(prefix + '_WEIGHT',weight)
    emit(prefix + '_GELU',0.5*a*(1.0+torch.tanh(math.sqrt(2.0/math.pi)*(a+0.044715*torch.pow(a,3.0)))))
    emit(prefix + '_RMS',(a.float()*torch.rsqrt(a.float().pow(2).mean(-1,keepdim=True)+1e-6)).to(dtype)*weight)
    emit(prefix + '_EULER',a+b*torch.tensor(-0.1777,dtype=dtype,device='cuda'))
    emit(prefix + '_MULTIPLY',a*b);emit(prefix + '_ADD',a+b)
    emit(prefix + '_BROADCAST_MULTIPLY',a*weight);emit(prefix + '_BROADCAST_ADD',a+weight)
    emit(prefix + '_ROW_MULTIPLY',a*torch.tensor([0.75,-0.25],dtype=dtype,device='cuda').view(2,1))
a=x.float();b=y.float()
emit('F32_GELU_FUSED',torch.nn.functional.gelu(a,approximate='tanh'))
emit('F32_GELU_EXACT',torch.nn.functional.gelu(a))
emit('F32_SILU',torch.nn.functional.silu(a))
emit('F32_GEGLU',torch.nn.functional.gelu(a,approximate='tanh')*b)
emit('F32_EULER_FUSED',a+b*(-0.1777))

# These inputs distinguish eager CUDA pow(x, 3.0) from a single final cast of
# an FP32 cube. PyTorch 2.11 specializes pow3 as scalar_t * scalar_t * scalar_t;
# BF16/F16 multiplication therefore rounds the square as well as the cube.
for dtype, prefix, samples in [
    (torch.bfloat16, 'BF16', [0.90625, 2.734375, -0.828125, -0.90625, -2.125, -2.453125, -2.734375]),
    (torch.float16, 'F16', [1.68359375, 1.701171875, -1.0791015625, -1.2734375, -1.373046875, -1.41796875, -1.4248046875, -1.6279296875, -1.630859375, -1.68359375, -1.6884765625, -1.701171875, -1.708984375, -1.80859375, -2.0546875]),
]:
    a = torch.tensor(samples, dtype=dtype, device='cuda')
    emit(prefix + '_POW3_SENSITIVE_X', a)
    emit(prefix + '_POW3_SENSITIVE_GELU', 0.5*a*(1.0+torch.tanh(math.sqrt(2.0/math.pi)*(a+0.044715*torch.pow(a,3.0)))))
    once_rounded_cube = (a.float()*a.float()*a.float()).to(dtype)
    emit(prefix + '_ONCE_ROUNDED_CUBE_GELU', 0.5*a*(1.0+torch.tanh(math.sqrt(2.0/math.pi)*(a+0.044715*once_rounded_cube))))
